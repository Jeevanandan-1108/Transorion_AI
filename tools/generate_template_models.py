from __future__ import annotations
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from invoice_extractor.extraction.chunked_extraction import build_field_chunks
from invoice_extractor.extraction.llm_extract import item_core_real_fields
from invoice_extractor.schema.field_naming import to_python_name
from invoice_extractor.schema.pydantic_models import is_number_type
from invoice_extractor.schema.schema import field_description_text, load_template_schema
from invoice_extractor.schema.templates_config import ITEM_SHEET_NAME, TEMPLATE_PATH

OUT_DIR = Path(__file__).resolve().parents[1] / "invoice_extractor" / "schema" / "generated"


def _class_name(shipment_type: str, sheet: str, index: int) -> str:
    base = to_python_name(f"{shipment_type}_{sheet}")
    pascal = "".join(part.capitalize() for part in base.split("_") if part)
    return f"{pascal}Chunk{index}Row"


def generate(shipment_type: str) -> Path:
    schema = load_template_schema(TEMPLATE_PATH[shipment_type])
    item_sheet_name = ITEM_SHEET_NAME[shipment_type]
    exclude = {item_sheet_name: item_core_real_fields(shipment_type)}
    chunks = build_field_chunks(schema, exclude=exclude, item_sheet_name=item_sheet_name)

    lines = [
        '"""',
        f"Auto-generated by tools/generate_template_models.py for shipment_type={shipment_type!r}.",
        "DO NOT hand-edit the field list, aliases, or types here -- they are re-derived from the",
        "template's own columns (schema.py) every time the generator runs, and a hand edit here",
        "would silently stop matching the real template the next time someone regenerates this",
        "file. The one thing meant to be hand-edited is each field's `description=` text.",
        '"""',
        "from __future__ import annotations",
        "from typing import Optional",
        "from pydantic import BaseModel, ConfigDict, Field",
        "",
        "",
    ]

    chunk_classes: dict[tuple[str, int], str] = {}
    for chunk in chunks:
        cls_name = _class_name(shipment_type, chunk.sheet, chunk.index)
        chunk_classes[(chunk.sheet, chunk.index)] = cls_name

        lines.append(f"class {cls_name}(BaseModel):")
        lines.append(f'    """Sheet {chunk.sheet!r}, chunk {chunk.index} ({len(chunk.fields)} field(s)).')
        lines.append('    ')
        lines.append('    Field names below are Python-safe versions of the template\'s own real')
        lines.append('    column names -- see each field\'s `alias=` for the exact column name the')
        lines.append('    LLM is asked for and the wire format actually uses; validate.py\'s mappers')
        lines.append('    never see these Python attribute names, only the alias.')
        lines.append('    """')
        lines.append("    model_config = ConfigDict(populate_by_name=True)")

        taken: set[str] = set()
        if chunk.link_field:
            py_name = to_python_name(chunk.link_field, taken)
            desc = (
                "Row/item identifier this data belongs to -- copy EXACTLY as printed, matching "
                "the same identifier used elsewhere on this document for that row, so this answer "
                "can be matched back to the right row afterward."
            )
            lines.append(
                f"    {py_name}: Optional[str] = Field(default=None, alias={chunk.link_field!r}, "
                f"description={desc!r})"
            )

        for field in chunk.fields:
            py_name = to_python_name(field, taken)
            py_type = "Optional[float | str]" if is_number_type(chunk.types.get(field, "string")) else "Optional[str]"
            desc = field_description_text(field, chunk.aliases, chunk.descriptions)
            lines.append(
                f"    {py_name}: {py_type} = Field(default=None, alias={field!r}, "
                f"description={desc!r})"
            )
        lines.append("")
        lines.append("")

    lines.append(f"# Looked up by chunked_extraction.py as (sheet_name, chunk_index) -> row model.")
    lines.append("CHUNK_MODELS = {")
    for (sheet, index), cls_name in chunk_classes.items():
        lines.append(f"    ({sheet!r}, {index}): {cls_name},")
    lines.append("}")
    lines.append("")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    init_path = OUT_DIR / "__init__.py"
    if not init_path.exists():
        init_path.write_text(
            '"""Generated per-template Pydantic model files -- see '
            'tools/generate_template_models.py. Do not hand-write files here directly."""\n',
            encoding="utf-8",
        )
    out_path = OUT_DIR / f"{shipment_type}.py"
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out_path


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("shipment_type", nargs="?", help="Template type name (see templates_config.TEMPLATE_PATH)")
    ap.add_argument("--all", action="store_true", help="Generate for every discovered template")
    args = ap.parse_args()

    if args.all:
        targets = sorted(TEMPLATE_PATH)
    elif args.shipment_type:
        targets = [args.shipment_type]
    else:
        ap.error("pass a shipment_type, or --all")
        return

    for t in targets:
        if t not in TEMPLATE_PATH:
            print(f"[skip] {t!r} is not a known template -- available: {', '.join(sorted(TEMPLATE_PATH))}")
            continue
        path = generate(t)
        print(f"[ok] {t} -> {path}")


if __name__ == "__main__":
    main()
